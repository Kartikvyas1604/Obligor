#!/usr/bin/env bash
#
# Local escrow bring-up for Obligor.
#
#   scripts/escrow-local.sh
#
# Starts a solana-test-validator, funds a provider wallet + a dedicated clearing
# authority, builds the obligor-escrow program and deploys it, then writes
# .escrow-local.env describing the live wiring. Idempotent: re-running reuses
# the running validator, wallet, and authority keypair.
#
# Then exercise it end to end with:
#   set -a; . ./.escrow-local.env; set +a
#   npm run verify:escrow
#
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

RPC="${SOLANA_RPC_URL:-http://127.0.0.1:8899}"
LEDGER="${ESCROW_LEDGER:-$ROOT/target/escrow-local-ledger}"
PROVIDER_WALLET="${ANCHOR_WALLET:-$HOME/.config/solana/id.json}"
AUTH_KEYPAIR="${SOLANA_AUTHORITY_KEYPAIR:-$ROOT/target/deploy/clearing-authority.json}"
PROGRAM_KEYPAIR="$ROOT/target/deploy/obligor_escrow-keypair.json"

log() { printf '\033[1;36m▸ %s\033[0m\n' "$*"; }
die() { printf '\033[1;31m✗ %s\033[0m\n' "$*" >&2; exit 1; }

command -v solana             >/dev/null || die "solana CLI not found"
command -v solana-keygen      >/dev/null || die "solana-keygen not found"
command -v solana-test-validator >/dev/null || die "solana-test-validator not found"
command -v anchor             >/dev/null || die "anchor CLI not found"

# ---- 1. validator -----------------------------------------------------------
if solana cluster-version --url "$RPC" >/dev/null 2>&1; then
  log "solana-test-validator already up at $RPC"
else
  log "starting solana-test-validator at $RPC (ledger: $LEDGER)"
  mkdir -p "$LEDGER"
  solana-test-validator --ledger "$LEDGER" --reset --quiet >/tmp/obligor-validator.log 2>&1 &
  for _ in $(seq 1 60); do
    solana cluster-version --url "$RPC" >/dev/null 2>&1 && break
    sleep 1
  done
  solana cluster-version --url "$RPC" >/dev/null 2>&1 || die "validator did not come up (see /tmp/obligor-validator.log)"
fi

# ---- 2. wallets -------------------------------------------------------------
[ -f "$PROVIDER_WALLET" ] || {
  log "generating provider wallet at $PROVIDER_WALLET"
  mkdir -p "$(dirname "$PROVIDER_WALLET")"
  solana-keygen new --no-bip39-passphrase -s -o "$PROVIDER_WALLET" >/dev/null
}
PROVIDER_ADDR="$(solana address -k "$PROVIDER_WALLET")"
log "airdrop → provider $PROVIDER_ADDR"
solana airdrop 500 "$PROVIDER_ADDR" --url "$RPC" >/dev/null 2>&1 || true

[ -f "$AUTH_KEYPAIR" ] || {
  log "generating clearing-authority keypair at $AUTH_KEYPAIR"
  mkdir -p "$(dirname "$AUTH_KEYPAIR")"
  solana-keygen new --no-bip39-passphrase -s -o "$AUTH_KEYPAIR" >/dev/null
}
AUTH_ADDR="$(solana address -k "$AUTH_KEYPAIR")"
log "airdrop → clearing authority $AUTH_ADDR"
solana airdrop 100 "$AUTH_ADDR" --url "$RPC" >/dev/null 2>&1 || true

# ---- 3. build + deploy ------------------------------------------------------
log "anchor build -p obligor-escrow"
anchor build -p obligor-escrow

log "anchor deploy -p obligor-escrow → $RPC"
anchor deploy -p obligor-escrow \
  --provider.cluster "$RPC" \
  --provider.wallet "$PROVIDER_WALLET"

PROGRAM_ID="$(solana address -k "$PROGRAM_KEYPAIR")"
PROGRAM_ID="${PROGRAM_ID:-94YmMnGjq2U8zpsLMSuk9fMwnfcHqrft3CtmwuZidMkZ}"

# ---- 4. emit env wiring -----------------------------------------------------
cat > "$ROOT/.escrow-local.env" <<EOF
# Generated by scripts/escrow-local.sh — localnet only. Do not commit.
ESCROW_REAL_SETTLE=true
SOLANA_RPC_URL=$RPC
ESCROW_PROGRAM_ID=$PROGRAM_ID
SOLANA_AUTHORITY_KEYPAIR=$AUTH_KEYPAIR
SOLANA_COMMITMENT=confirmed
ESCROW_BASE_DECIMALS=6
EOF

log "escrow deployed: $PROGRAM_ID"
log "wrote $ROOT/.escrow-local.env"
log "next:  set -a; . ./.escrow-local.env; set +a; npm run verify:escrow"
